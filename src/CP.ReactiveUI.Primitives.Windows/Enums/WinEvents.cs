    /// <summary>
    ///     NOTES:
    ///     There is only one "focused" child item in a parent.  This is the place
    ///     keystrokes are going at a given moment.  Hence only send a notification
    ///     about where the NEW focus is going.  A NEW item getting the focus already
    ///     implies that the OLD item is losing it.
    ///     SELECTION however can be multiple.  Hence the different SELECTION
    ///     notifications.  Here's when to use each:
    ///     (1) Send a SELECTION notification in the simple single selection
    ///     case (like the focus) when the item with the selection is
    ///     merely moving to a different item within a container.  windowHandle + ID
    ///     is the container control, idChildItem is the new child with the
    ///     selection.
    ///     (2) Send a SELECTIONADD notification when a new item has simply been added
    ///     to the selection within a container.  This is appropriate when the
    ///     number of newly selected items is very small.  windowHandle + ID is the
    ///     container control, idChildItem is the new child added to the selection.
    ///     (3) Send a SELECTIONREMOVE notification when a new item has simply been
    ///     removed from the selection within a container.  This is appropriate
    ///     when the number of newly selected items is very small, just like
    ///     SELECTIONADD.  windowHandle + ID is the container control, idChildItem is the
    ///     new child removed from the selection.
    ///     (4) Send a SELECTIONWITHIN notification when the selected items within a
    ///     control have changed substantially.  Rather than propagate a large
    ///     number of changes to reflect removal for some items, addition of
    ///     others, just tell somebody who cares that a lot happened.  It will
    ///     be faster an easier for somebody watching to just turn around and
    ///     query the container control what the new bunch of selected items
    ///     are.
    /// </summary>
    EVENT_OBJECT_SELECTION = 32_774U,
    /// <summary>Represents the EVENT_OBJECT_SELECTIONADD value.</summary>
    EVENT_OBJECT_SELECTIONADD = 32_775U,
    /// <summary>Represents the EVENT_OBJECT_SELECTIONREMOVE value.</summary>
